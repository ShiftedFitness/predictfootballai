/**
 * matchup-page.js — the ask box on a matchup page.
 *
 * The page itself is complete static HTML: the shared players, the seasons the
 * two clubs met and both records are all in the file before this runs. This is
 * only the question box, which cannot be static by definition.
 *
 * A near-copy of the ask wiring in team-page.js rather than a shared module,
 * and that is a judgement worth stating: the two pages have different element
 * ids and different analytics context, and a shared module with two callers
 * and three options would be more code than the twenty lines it saves. If a
 * third page grows an ask box, that is the moment to extract it.
 */
(function () {
  'use strict';

  var M = window.TS_MATCHUP;
  var f = document.getElementById('askForm');
  if (!M || !f) return;

  var API = (location.hostname === 'localhost' || location.hostname === '127.0.0.1')
    ? 'http://localhost:8888/.netlify/functions' : '/.netlify/functions';

  var out = document.getElementById('askAnswer');
  var input = document.getElementById('askQ');

  function esc(s) {
    return String(s == null ? '' : s).replace(/[&<>"]/g, function (ch) {
      return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[ch];
    });
  }

  [].slice.call(document.querySelectorAll('.ask-examples button')).forEach(function (b) {
    b.addEventListener('click', function () {
      input.value = b.dataset.q;
      f.requestSubmit ? f.requestSubmit() : f.dispatchEvent(new Event('submit'));
    });
  });

  f.addEventListener('submit', function (e) {
    e.preventDefault();
    var q = input.value.trim();
    if (!q) return;
    out.innerHTML = '<p class="msg">Looking…</p>';
    fetch(API + '/ask', {
      method: 'POST', headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ question: q, source: 'matchup_page' }),
    }).then(function (r) { return r.json(); }).then(function (d) {
      var html = '<p class="msg">' + esc(d.message || d.error) + '</p>';
      if (d.rows && d.rows.length) {
        html += '<table><tbody>' + d.rows.slice(0, 10).map(function (r) {
          var right = r.clubs && r.clubs[0] && r.clubs[0].team
            ? r.clubs.map(function (c) { return esc(c.team) + ' ' + c.appearances; }).join(' · ')
            : (r.appearances != null ? r.appearances + ' apps, ' + r.goals + 'g' : '');
          return '<tr><td>' + esc(r.player || r.name) + '</td><td>' + right + '</td></tr>';
        }).join('') + '</tbody></table>';
      }
      if (d.provenance) {
        html += '<p class="prov">From the TeleStats database in ' +
                esc(d.provenance.query_ms) + 'ms · <a href="/tools/data.html">coverage</a></p>';
      }
      out.innerHTML = html;
      // Structured only — the question text never goes to analytics.
      if (d.analytics && window.TSAnalytics) TSAnalytics.trackEvent?.('ask_query', d.analytics);
    }).catch(function () {
      out.innerHTML = '<p class="msg">Could not reach the database. Try again.</p>';
    });
  });

  // Revealing the shared-player list is the closest thing this page has to a
  // round of play, so it is worth knowing how often it happens. The slug is
  // generated by this codebase, never user text.
  var reveal = document.querySelector('details.reveal');
  if (reveal) {
    reveal.addEventListener('toggle', function once() {
      if (!reveal.open) return;
      reveal.removeEventListener('toggle', once);
      if (window.TSAnalytics) TSAnalytics.trackEvent?.('matchup_reveal', { matchup: M.slug });
    });
  }
})();
